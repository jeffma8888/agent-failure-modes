#!/usr/bin/env python3
"""afm - query the agent-failure-modes corpus without loading it whole.

Stdlib only. Reads data/incidents.json and data/catalog.json (both generated by
tools/build.py) and runs from any working directory.

  search "text" [-k 8] [--class C]   incidents ranked by BM25F over title, signature,
                                     root cause, rule and what
  route "text" [-k 5]                catalog nodes ranked by their matching incidents
                                     (discounted sum) plus their own routing text
  check "draft title + signature + root cause" [-k 5]
                                     candidate duplicates before you file a new one
  top [-n 20]                        the most-recurrent failures
  show INC-XXXX [--rule]             print an incident page, or only its rule
  next-id                            the next free id (fetch origin first)

`check` prints RANKED CANDIDATES, never a verdict: lexical similarity of a repeat
and of a near neighbour overlap, so no threshold separates them honestly. Read the
top pages and decide: same mechanism AND same rule means a recurrence.
"""
from __future__ import annotations
import argparse, json, math, os, re, subprocess, sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEV_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3}
SEARCH_WEIGHTS = {"title": 3.0, "signature": 2.5, "rule": 1.5, "root_cause": 1.5, "what": 1.0}
CHECK_WEIGHTS = {"title": 2.0, "signature": 2.0, "root_cause": 1.5, "rule": 1.0, "what": 0.5}
NODE_WEIGHTS = {"title": 2.0, "text": 1.0}
K1, B = 1.2, 0.75
ROUTE_POOL = 40          # incident hits aggregated per node by `route`
DECISION = "same mechanism AND same rule: add a recurrence to it, else new incident"
STOP = frozenset("""
a about above after again against all also am an and any are as at be because been before
being below between both but by can could did do does doing down during each few for from
further had has have having he her here hers him his how i if in into is it its itself just
me more most my no nor not of off on once only or other our ours out over own same she should
so some such than that the their theirs them then there these they this those through to too
under until up very was we were what when where which while who whom why will with would you
your yours one two its it's per via""".split())


# --------------------------------------------------------------------------- text

def stem(w: str) -> str:
    """A deliberately light suffix stripper: plural, -ing, -ed, trailing e."""
    if len(w) > 4 and w.endswith("ies"):
        w = w[:-3] + "y"
    elif len(w) > 4 and w.endswith("sses"):
        w = w[:-2]
    elif len(w) > 3 and w.endswith("s") and not w.endswith(("ss", "us", "is")):
        w = w[:-1]
    for suf in ("ing", "ed"):
        if w.endswith(suf) and len(w) - len(suf) >= 3:
            w = w[: -len(suf)]
            if len(w) > 3 and w[-1] == w[-2] and w[-1] not in "lsz":
                w = w[:-1]
            break
    if len(w) > 3 and w.endswith("e"):
        w = w[:-1]
    return w


def tokens(text: str) -> list[str]:
    return [stem(t) for t in re.findall(r"[a-z0-9]+", (text or "").lower())
            if t not in STOP and (len(t) > 1 or t.isdigit())]


class BM25F:
    """BM25F: per-field length normalisation, field-weighted term frequency."""

    def __init__(self, docs: list[dict], weights: dict[str, float]):
        self.n = len(docs)
        per_doc = []
        totals = defaultdict(int)
        for d in docs:
            fields = {f: Counter(tokens(d.get(f, ""))) for f in weights}
            lens = {f: sum(c.values()) for f, c in fields.items()}
            for f, n in lens.items():
                totals[f] += n
            per_doc.append((fields, lens))
        avg = {f: (totals[f] / self.n) if self.n else 0.0 for f in weights}
        self.wtf: list[dict[str, float]] = []
        df = Counter()
        for fields, lens in per_doc:
            acc: dict[str, float] = defaultdict(float)
            for f, counts in fields.items():
                norm = 1 - B + B * (lens[f] / avg[f] if avg[f] else 0.0)
                for t, c in counts.items():
                    acc[t] += weights[f] * c / norm
            self.wtf.append(dict(acc))
            df.update(acc.keys())
        self.idf = {t: math.log(1 + (self.n - k + 0.5) / (k + 0.5)) for t, k in df.items()}

    def scores(self, query: str) -> list[float]:
        q = set(tokens(query))
        out = []
        for w in self.wtf:
            s = 0.0
            for t in q:
                x = w.get(t)
                if x:
                    s += self.idf[t] * x / (K1 + x)
            out.append(s)
        return out


class Cosine:
    """TF-IDF cosine similarity in [0, 1], field-weighted, sublinear tf."""

    def __init__(self, docs: list[dict], weights: dict[str, float]):
        raw = []
        df = Counter()
        for d in docs:
            acc: dict[str, float] = defaultdict(float)
            for f, w in weights.items():
                for t in tokens(d.get(f, "")):
                    acc[t] += w
            raw.append(acc)
            df.update(acc.keys())
        n = len(docs)
        self.idf = {t: math.log((n + 1) / (k + 1)) + 1 for t, k in df.items()}
        self.default_idf = math.log(n + 1) + 1
        self.vecs = []
        for acc in raw:
            v = {t: (1 + math.log(x)) * self.idf[t] for t, x in acc.items() if x >= 1} | \
                {t: x * self.idf[t] for t, x in acc.items() if x < 1}
            norm = math.sqrt(sum(x * x for x in v.values())) or 1.0
            self.vecs.append({t: x / norm for t, x in v.items()})

    def scores(self, query: str) -> list[float]:
        tf = Counter(tokens(query))
        q = {t: (1 + math.log(c)) * self.idf.get(t, self.default_idf) for t, c in tf.items()}
        norm = math.sqrt(sum(x * x for x in q.values())) or 1.0
        return [sum(x * v.get(t, 0.0) for t, x in q.items()) / norm for v in self.vecs]


# --------------------------------------------------------------------------- data

def load(root: str = ROOT) -> dict:
    try:
        inc = json.load(open(os.path.join(root, "data", "incidents.json"), encoding="utf-8"))
        cat = json.load(open(os.path.join(root, "data", "catalog.json"), encoding="utf-8"))
    except FileNotFoundError as exc:
        raise SystemExit(f"afm: {exc.filename} is missing; run python3 tools/build.py first")
    if inc.get("schema", 1) < 2:
        raise SystemExit("afm: data/incidents.json is schema 1; run python3 tools/build.py")
    return {"root": root, "incidents": inc["incidents"], "classes": inc["classes"],
            "topics": inc.get("topics", {}), "catalog": cat,
            "byid": {i["id"]: i for i in inc["incidents"]}}


def where(inc: dict) -> str:
    return inc.get("topic") or inc["classes"][0]


def rank_key(inc: dict):
    return (-inc["occurrences"], SEV_ORDER.get(inc["severity"], 9), inc["id"])


def _index(data: dict, kind: str):
    cache = data.setdefault("_idx", {})
    if kind not in cache:
        cache[kind] = (BM25F(data["incidents"], SEARCH_WEIGHTS) if kind == "search"
                       else Cosine(data["incidents"], CHECK_WEIGHTS))
    return cache[kind]


def search(data: dict, text: str, k: int = 8, cls: str | None = None) -> list[tuple[dict, float]]:
    scores = _index(data, "search").scores(text)
    hits = [(inc, s) for inc, s in zip(data["incidents"], scores)
            if s > 0 and (cls is None or cls in inc["classes"])]
    hits.sort(key=lambda h: (-h[1], h[0]["id"]))
    return hits[:k]


def route(data: dict, text: str, k: int = 5) -> list[dict]:
    """Rank catalog nodes. A node's score is the harmonic-discounted sum of its incident
    hits (best hit counts fully, the 2nd half, the 3rd a third...) so a big node does not
    win on volume alone, plus the score of the node's own routing text."""
    agg: dict[str, dict] = {}
    for inc, s in search(data, text, ROUTE_POOL):
        node = agg.setdefault(inc["node"], {"node": inc["node"], "where": where(inc), "score": 0.0, "ids": []})
        node["ids"].append(inc["id"])
        node["score"] += s / len(node["ids"])
    # The nodes' own text was written for routing: score it like one more hit.
    cat = data["catalog"]
    nodes = []
    for c, meta in data["classes"].items():
        nodes.append({"node": cat["classes"][c]["node"], "where": c, "title": c,
                      "text": " ".join(meta.get(f, "") for f in ("route", "what", "ask"))})
    for key, meta in data["topics"].items():
        nodes.append({"node": cat["topics"][key]["node"], "where": key, "title": meta["title"],
                      "text": meta["go_here_if"] + " " + meta["rule"]})
    for n, s in zip(nodes, BM25F(nodes, NODE_WEIGHTS).scores(text)):
        if s > 0:
            agg.setdefault(n["node"], {"node": n["node"], "where": n["where"], "score": 0.0, "ids": []})
            agg[n["node"]]["score"] += s
    ranked = sorted(agg.values(), key=lambda a: (-a["score"], a["node"]))
    return ranked[:k]


def check(data: dict, text: str, k: int = 5) -> list[dict]:
    """Candidate canonicals for a draft. A recurrence record counts for its canonical."""
    best: dict[str, dict] = {}
    for inc, s in zip(data["incidents"], _index(data, "check").scores(text)):
        cid = inc.get("recurrence_of") or inc["id"]
        if cid not in best or s > best[cid]["similarity"]:
            best[cid] = {"incident": data["byid"][cid], "similarity": s,
                         "via": inc["id"] if inc["id"] != cid else None}
    ranked = sorted(best.values(), key=lambda b: (-b["similarity"], b["incident"]["id"]))
    return ranked[:k]


def top(data: dict, n: int = 20) -> list[dict]:
    return sorted((i for i in data["incidents"] if not i.get("recurrence_of")), key=rank_key)[:n]


def normalize_id(raw: str) -> str:
    m = re.fullmatch(r"(?:inc-?)?(\d{1,4})", raw.strip(), re.IGNORECASE)
    return f"INC-{int(m.group(1)):04d}" if m else raw.strip()


def next_id(data: dict) -> tuple[str, str | None]:
    local = max((int(i["id"][4:]) for i in data["incidents"]), default=0)
    remote = None
    try:
        out = subprocess.run(["git", "-C", data["root"], "show", "origin/main:data/incidents.json"],
                             capture_output=True, text=True, timeout=20)
        if out.returncode == 0:
            ids = [int(i["id"][4:]) for i in json.loads(out.stdout).get("incidents", [])]
            remote = max(ids, default=0)
    except (OSError, ValueError, subprocess.SubprocessError):
        remote = None
    warn = None
    if remote is not None and remote > local:
        warn = (f"origin/main already has INC-{remote:04d}, ahead of this checkout: rebase "
                "onto origin/main before adding an incident")
    return f"INC-{max(local, remote or 0) + 1:04d}", warn


# --------------------------------------------------------------------------- CLI

def _print_incident(inc: dict, extra: str = "") -> None:
    rec = f"  recurrence of {inc['recurrence_of']}" if inc.get("recurrence_of") else ""
    print(f"{inc['id']}  n={inc['occurrences']}  {where(inc)}  [{inc['severity']}]{extra}{rec}")
    print(f"  {inc['title']}")
    print(f"  rule: {inc['rule']}")
    print(f"  {inc['file']}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="afm.py", description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog="Every path printed is relative to the repository root.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("search", help="incidents matching a text")
    p.add_argument("text")
    p.add_argument("-k", type=int, default=8)
    p.add_argument("--class", dest="cls")
    p = sub.add_parser("route", help="catalog nodes for a symptom")
    p.add_argument("text")
    p.add_argument("-k", type=int, default=5)
    p = sub.add_parser("check", help="candidate duplicates for a draft incident")
    p.add_argument("text")
    p.add_argument("-k", type=int, default=5)
    p = sub.add_parser("top", help="most-recurrent failures")
    p.add_argument("-n", type=int, default=20)
    p = sub.add_parser("show", help="print an incident page")
    p.add_argument("id")
    p.add_argument("--rule", action="store_true", help="print only the rule")
    sub.add_parser("next-id", help="next free incident id")
    a = ap.parse_args(argv)
    data = load()

    if a.cmd == "search":
        if a.cls and a.cls not in data["classes"]:
            print(f"afm: unknown class {a.cls!r}; classes: {', '.join(data['classes'])}", file=sys.stderr)
            return 2
        hits = search(data, a.text, a.k, a.cls)
        if not hits:
            print("no matching incidents")
        for inc, s in hits:
            _print_incident(inc, f"  score {s:.2f}")
        return 0

    if a.cmd == "route":
        nodes = route(data, a.text, a.k)
        if not nodes:
            print("no matching node; start at catalog/README.md")
        for n, r in enumerate(nodes, 1):
            if r["where"] in data["topics"]:
                label = data["topics"][r["where"]]["title"]
            else:
                meta = data["classes"][r["where"]]
                label = meta.get("route") or re.split(r"(?<=[.!?])\s+", meta["what"], maxsplit=1)[0]
            ids = f"  hits: {', '.join(r['ids'][:6])}" if r["ids"] else ""
            print(f"{n}. {r['node']}  score {r['score']:.2f}")
            print(f"   {r['where']} - {label}{ids}")
        return 0

    if a.cmd == "check":
        print("Candidate duplicates, ranked. Similarity is lexical (cosine, 0-1) and is NOT a verdict.")
        for n, c in enumerate(check(data, a.text, a.k), 1):
            inc = c["incident"]
            via = f"  (via its recurrence record {c['via']})" if c["via"] else ""
            print(f"{n}. {inc['id']}  similarity {c['similarity']:.2f}  n={inc['occurrences']}  "
                  f"{where(inc)}  [{inc['severity']}]{via}")
            print(f"   {inc['title']}")
            print(f"   signature: {inc['signature']}")
            print(f"   rule: {inc['rule']}")
            print(f"   {inc['file']}")
        print(f"Read the top pages, then decide - {DECISION}.")
        print('A recurrence is {"date": "YYYY-MM-DD", "note": "max 300 chars"} appended to that '
              "incident's `recurrences` list in tools/corpus.py; then run python3 tools/build.py.")
        return 0

    if a.cmd == "top":
        rows = top(data, a.n)
        if rows and rows[0]["occurrences"] <= 1:
            print("(no repeats recorded yet: every failure has occurred once, so this falls back to "
                  "severity, then id)")
        for n, inc in enumerate(rows, 1):
            print(f"{n:>3}. {inc['id']}  n={inc['occurrences']}  [{inc['severity']}]  {where(inc)}  "
                  f"{inc['title']}")
        return 0

    if a.cmd == "show":
        iid = normalize_id(a.id)
        inc = data["byid"].get(iid)
        if not inc:
            print(f"afm: no incident {a.id!r}", file=sys.stderr)
            return 2
        if a.rule:
            rec = f" (recurrence of {inc['recurrence_of']})" if inc.get("recurrence_of") else ""
            print(f"{inc['id']} [{inc['severity']}]{rec}: {inc['rule']}")
            return 0
        sys.stdout.write(open(os.path.join(data["root"], inc["file"]), encoding="utf-8").read())
        return 0

    if a.cmd == "next-id":
        nid, warn = next_id(data)
        print(nid)
        print("reminder: git fetch origin and rebase first - two sessions once minted the same id. "
              "This checks the local origin/main as of the last fetch.", file=sys.stderr)
        if warn:
            print(f"WARNING: {warn}", file=sys.stderr)
        return 0
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
